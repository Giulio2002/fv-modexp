#!/usr/bin/env python3
"""gen-libne-twins64.py: generate the amd64 LibNE twins (agent expmc s73; amd64 version of gen-libne-twins.py) of
nat.expNN's machine-run path modules in continuation form: every theorem of <M> whose chunk mentions `LibN.program` is
(and every `def` whose chunk mentions it: continuation types) is copied renamed `<name>E`, `LibN.program` -> `LibNE.program`, references to twinned theorems renamed. The twin imports the
original (for its definitions/helpers) and LibNE. Usage: scripts/gen-libne-twins64.py [--check]
"""
import re, sys, os
D = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'lean', 'FvModexp', 'Proofs', 'Amd64', 'Exp')
TWINS = ['NPro', 'NTriv', 'NMk', 'NMkP', 'NDisp']
PFX = 'FvModexp.Proofs.Amd64.Exp.'
NS = 'FvModexp.Amd64.ExpN'

def chunks(m):
    src = open(os.path.join(D, m + '.lean')).read()
    head, _, body = src.partition('\nnamespace %s\n' % NS)
    body = body.rsplit('end %s' % NS, 1)[0]
    return head, re.split(r'\n\s*\n', body)

def first_line(c):
    for l in c.strip().splitlines():
        l = re.sub(r'^@\[[^\]]*\] ', '', l)
        if l.strip() and not l.startswith('set_option') and not l.startswith('/-') and not l.startswith('@[') \
                and not l.lstrip().startswith('-/') and not l.startswith(' '):
            return l
    return ''

allnames = {}
for m in TWINS:
    for c in chunks(m)[1]:
        mo = re.match(r'(?:private )?(?:theorem|def) (\w+)', first_line(c))
        if mo and 'LibN.program' in c: allnames[mo.group(1)] = mo.group(1) + 'E'

def gen(m):
    head, cs = chunks(m)
    keep = [c.strip('\n') for c in cs if re.match(r'(private )?(theorem|def) ', first_line(c)) and 'LibN.program' in c]
    out = '\n\n'.join(keep).replace('LibN.program', 'LibNE.program')
    out = re.sub(r'\b(' + '|'.join(map(re.escape, sorted(allnames, key=len, reverse=True))) + r')\b',
                 lambda mo: allnames[mo.group(1)], out)
    imps = [PFX + m] + [PFX + i[len(PFX):] + 'E' for i in re.findall(r'^import (\S+)', head, re.M)
                        if i.startswith(PFX) and i[len(PFX):] in TWINS] + [PFX + 'LibNE']
    opens = re.findall(r'^open .*$', head, re.M)
    hdr = '\n'.join('import ' + i for i in dict.fromkeys(imps))
    hdr += ('\n\n/-! GENERATED by scripts/gen-libne-twins64.py from `%s.lean` (do not edit): its theorems on '
            '`LibNE.program.link impl` (the recursive pair nat.expNN ↔ nat.expNNEven), names suffixed `E`. -/\n\n' % m)
    hdr += '\n'.join(opens) + '\n\nset_option autoImplicit false\n\nnamespace %s\n\n' % NS
    return hdr + out + '\n\nend %s\n' % NS

bad = 0
for m in TWINS:
    t = gen(m); p = os.path.join(D, m + 'E.lean')
    if '--check' in sys.argv:
        if not os.path.exists(p) or open(p).read() != t: print('DIFFERS', p); bad = 1
    elif not os.path.exists(p) or open(p).read() != t:
        open(p, 'w').write(t); print('wrote', p)
sys.exit(bad)
