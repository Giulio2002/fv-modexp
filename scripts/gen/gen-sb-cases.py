#!/usr/bin/env python3
"""Generate the per-length SetBytes summaries of the RequiredGas proof (arm64): lean/FvModexp/Proofs/Arm64/RG/Sb{A..G}.lean.
Each case `sbN : Summary Extracted.program sbA (SbPre N) (SbPost N)` (N = 0..32) runs the extracted SetBytes (and the SetBytesK it calls)
symbolically with the literal length N; adapted from fv-uint256 lean/Fv256/Proofs/Arm64/SbCases/Case*.lean.
usage: scripts/gen/gen-sb-cases.py   (rewrites the seven files)"""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
D = os.path.join(ROOT, 'lean/FvModexp/Proofs/Arm64/RequiredGas')
HDR = '''-- GENERATED by scripts/gen/gen-sb-cases.py (do not edit); adapted from fv-uint256 lean/Fv256/Proofs/Arm64/SbCases
import Extracted
import FvModexp.Proofs.Common.Util
import FvModexp.Proofs.Common.Ret
import FvModexp.Proofs.Arm64.RG.Defs

namespace FvModexp.Arm64.RG

open Janus Janus.Arm64 Janus.GoABI Janus.Tactic Janus.Spec Janus.Contracts

'''
def case(n):
    if n == 32:
        close = ('rw [Util.be32_rev, Util.rc_rev8 _ (Util.readLE8_lt _ _), Util.rc_rev8 _ (Util.readLE8_lt _ _), '
                 'Util.rc_rev8 _ (Util.readLE8_lt _ _), Util.rc_rev8 _ (Util.readLE8_lt _ _)]\n         omega')
    else:
        haves = '; '.join(('have := Util.rd1_lt s.mem ((s.regs 1).toNat + %d)' % i) if i else 'have := Util.rd1_lt s.mem (s.regs 1).toNat' for i in range(n))
        close = ((haves + '\n         ') if n else '') + \
            '(try simp only [Util.chunk8, Util.chunk4, Util.chunk2, Util.chunk2n, Util.rot0])\n         ' \
            'all_goals (simp only [Aux.fromBE, Nat.add_zero, Nat.reducePow, Nat.reduceAdd, Nat.add_assoc, Nat.zero_add]; ' \
            '(try simp (disch := omega) only [Util.or_hi16, Util.or_hi24, Util.or_hi32, Util.or_hi40, Util.or_hi48, Util.or_hi56, Nat.mod_eq_of_lt]); (try (first | (simp only [Nat.mul_add, Nat.mul_assoc, Nat.reduceMul, Nat.mul_one]; ac_rfl) | omega)))'
    return f'''set_option maxHeartbeats 64000000 in
set_option maxRecDepth 100000 in
set_option linter.unusedSimpArgs false in
theorem sb{n} : Summary Extracted.program sbA (SbPre {n}) (SbPost {n}) := by
  intro s hpc ⟨⟨hr1, hr2⟩, ⟨hg1, hg2, hg3⟩, ⟨hal, hb, ha, hw⟩, hd, hl, hlc, hc48, ⟨hz, hz'⟩, ⟨hp, hp'⟩, hd1, hd2, hd3, hdg⟩
  have hl' : s.regs 2 = BitVec.ofNat 64 {n} := BitVec.eq_of_toNat_eq (by simp [hl])
  janus_data hd [hw]
  simp only [Disjoint] at hd1 hd2 hd3 hdg
  janus_run
  all_goals first
    | (exfalso; omega)
    | (refine Ret.retX_intro rfl rfl rfl rfl rfl rfl rfl rfl rfl (fun i hi => ?_) (by janus_frame) ⟨?_, ?_⟩
       · simp at hi; subst hi; rfl
       · janus_simp
         {close}
       · dl_close)

'''
# groups balanced by elaboration time (the longer lengths cost more), so that no module is on the row's critical path for long
GROUPS = (('SbA', range(0, 13)), ('SbB', range(13, 19)), ('SbC', range(19, 23)), ('SbD', range(23, 26)), ('SbE', range(26, 29)),
          ('SbF', range(29, 31)), ('SbG', range(31, 33)))
for name, rng in GROUPS:
    with open(os.path.join(D, name + '.lean'), 'w') as f:
        f.write(HDR + ''.join(case(n) for n in rng) + 'end FvModexp.Arm64.RG\n')
