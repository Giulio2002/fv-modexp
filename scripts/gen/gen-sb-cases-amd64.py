#!/usr/bin/env python3
"""Generate the per-length SetBytes summaries of the RequiredGas proof (amd64): lean/FvModexp/Proofs/Amd64/RG/Sb{A..G}.lean.
Each case `sbN : Summary Extracted.program sbA (SbPre N) (SbPost N)` (N = 0..32) runs the extracted SetBytes (and the SetBytesK it calls)
symbolically with the literal length N. The per-case value closers are taken from fv-uint256 lean/Fv256/Proofs/Amd64/SbCases/Case<N>.lean
(adapted: `ptr` is `RBX`, `Spec.fromBE` is `Aux.fromBE`); the length-32 closer follows CaseBig.lean.
usage: scripts/gen/gen-sb-cases-amd64.py [FVU_ROOT]   (default /srv/fvu-master; rewrites the seven files)"""
import os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FVU = sys.argv[1] if len(sys.argv) > 1 else '/srv/fvu-master'
D = os.path.join(ROOT, 'lean/FvModexp/Proofs/Amd64/RG')
HDR = '''-- GENERATED by scripts/gen/gen-sb-cases-amd64.py (do not edit); adapted from fv-uint256 lean/Fv256/Proofs/Amd64/SbCases
import Extracted
import FvModexp.Proofs.Common.Util
import FvModexp.Proofs.Amd64.RG.Defs

namespace FvModexp.Amd64.RG

open Janus Janus.Amd64 Janus.Amd64.GoABI Janus.Amd64.Tactic Janus.Spec Janus.Contracts

'''
P = '(s.regs 3).toNat'
def closer(n):
    if n == 32:
        return (f'(try simp only [show 32 + {P} - 8 = {P} + 24 from by omega, show 32 + {P} - 16 = {P} + 16 from by omega, '
                f'show 32 + {P} - 24 = {P} + 8 from by omega, show 32 + {P} - 32 = {P} from by omega])\n'
                '         rw [Util.be32_rev]\n'
                f'         have h1 := Util.revBytes_lt 8 (s.mem.readLE {P} 8)\n'
                f'         have h2 := Util.revBytes_lt 8 (s.mem.readLE ({P} + 8) 8)\n'
                f'         have h3 := Util.revBytes_lt 8 (s.mem.readLE ({P} + 16) 8)\n'
                f'         have h4 := Util.revBytes_lt 8 (s.mem.readLE ({P} + 24) 8)\n'
                '         simp only [Nat.reducePow] at h1 h2 h3 h4\n'
                '         omega')
    src = open(os.path.join(FVU, f'lean/Fv256/Proofs/Amd64/SbCases/Case{n}.lean')).read()
    key = 'Util.ow2_self_iff]⟩\n'
    i = src.index(key) + len(key)
    body = src[i:].rsplit('end Fv256', 1)[0].rstrip()
    assert body.endswith('))'), n
    body = body[:-1].strip()          # drop the closing paren of `| (refine ...`
    body = body.replace('ptr.toNat', P).replace('Spec.fromBE', 'Aux.fromBE')
    return body
def case(n):
    return f'''set_option maxHeartbeats 64000000 in
set_option maxRecDepth 100000 in
set_option linter.unusedSimpArgs false in
theorem sb{n} : Summary Extracted.program sbA (SbPre {n}) (SbPost {n}) := by
  intro s hpc ⟨⟨hra, hra2, hra3⟩, hg, ⟨hlow, hnw, hacc⟩, hx15, hd, hl, hlc, hc48, ⟨hzw, hz⟩, ⟨hpw, hp⟩, hd1, hd2, hd3, hdg⟩
  have hl' : s.regs 1 = BitVec.ofNat 64 {n} := BitVec.eq_of_toNat_eq (by simp [hl])
  have hgl := hg.load
  have hgb := hg.below
  have hnw2 := hg.noWrap
  have hgr := hg.readable
  simp only [regSP, regG, stackguard0Offset, stackguard0] at hgl hgb hnw2 hgr hacc hlow hnw hd2 hd3 hdg
  janus64_data hd [hacc]
  simp only [Janus.Spec.Disjoint] at hd1 hd2 hd3
  janus64_run [Util.readLE_32]
  all_goals first
    | (exfalso; omega)
    | (refine Ret64.ret_intro rfl rfl rfl rfl rfl rfl rfl rfl rfl rfl rfl rfl rfl (by janus_frame) ⟨?_, ?_⟩
       · simp only [val256, Util.readLE_32]
         janus64_simp
         {closer(n)}
       · dl_close)

'''
GROUPS = (('SbA', range(0, 13)), ('SbB', range(13, 19)), ('SbC', range(19, 23)), ('SbD', range(23, 26)), ('SbE', range(26, 29)),
          ('SbF', range(29, 31)), ('SbG', range(31, 33)))
for name, rng in GROUPS:
    with open(os.path.join(D, name + '.lean'), 'w') as f:
        f.write(HDR + ''.join(case(n) for n in rng) + 'end FvModexp.Amd64.RG\n')
