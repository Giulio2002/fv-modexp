#!/usr/bin/env python3
"""port-sqrdefs-amd64.py: one-pass port of lean/FvModexp/Proofs/Arm64/Nat/SqrDefs.lean (statement layer of the squaring
SCC) to amd64 (agent divmc s29; in the style of agent infra's port-p2w4.py). Mechanical substitutions only: namespaces,
g register (X28 -> R14), window form (winA -> win), entry addresses, the Go amd64 argument/result registers
(AX BX CX DI SI R8 R9 = regs 0 3 1 7 6 8 9; results AX BX CX = regs 0 3 1), the return address on the stack, the
callee-saved set (RegsOK: RSP+8, RBP, R14, X15) and the AMD64 DF CONVENTION (posts state fsBase/DF unchanged).
Frame sizes are ISA-identical (nat.sqr 176, karatsubaSqr 320, spills 64/48), so Common/SqrCost's windows/costs apply."""
import sys, re
src, dst = sys.argv[1], sys.argv[2]
s = open(src).read()
rep = [
  ("import FvModexp.Proofs.Arm64.", "import FvModexp.Proofs.Amd64."),
  ("open Janus Janus.Arm64 Janus.GoABI Janus.Tactic Janus.Spec Janus.Contracts",
   "open Janus Janus.Amd64 Janus.Amd64.GoABI Janus.Amd64.Tactic Janus.Spec Janus.Contracts"),
  ("namespace FvModexp.Arm64.NatSqr", "namespace FvModexp.Amd64.NatSqr"),
  ("open FvModexp.Arm64.RunIface", "open FvModexp.Amd64.RunIface"),
  ("end FvModexp.Arm64.NatSqr", "end FvModexp.Amd64.NatSqr"),
  ("(s.regs 28).toNat", "(s.regs 14).toNat"),
  ("winA s W", "win s W"),
  ("(impl : List Segment)", "(impl : List Amd64.Segment)"),
  ("| (false, _) => 0x1bb420", "| (false, _) => 0x5f0fe0"),
  ("| (true, _) => 0x1bc2b0", "| (true, _) => 0x5f2380"),
  ("segAddr Extracted.program fn = 0x1bb420", "segAddr Extracted.program fn = 0x5f0fe0"),
  ("segAddr Extracted.program fnK = 0x1bc2b0", "segAddr Extracted.program fnK = 0x5f2380"),
  ("(m : Memory)", "(m : Arm64.Memory)"),
]
for a, b in rep:
    assert a in s, a
    s = s.replace(a, b)
# results in AX, BX, CX (regs 0, 3, 1)
old = "∃ (p' l' c' : Nat), s'.regs 0 = BitVec.ofNat 64 p' ∧ s'.regs 1 = BitVec.ofNat 64 l' ∧\n    s'.regs 2 = BitVec.ofNat 64 c' ∧"
assert old in s
s = s.replace(old, "s'.fsBase = s.fsBase ∧ s'.df = s.df ∧\n  ∃ (p' l' c' : Nat), s'.regs 0 = BitVec.ofNat 64 p' ∧ s'.regs 3 = BitVec.ofNat 64 l' ∧\n    s'.regs 1 = BitVec.ofNat 64 c' ∧")
old = "  natVal s'.mem zp zl = natVal s.mem xp xl * natVal s.mem xp xl ∧\n    ∃ (L' : List (Nat × Nat)) (b' : Nat), LiveExt R L L' ∧ b - ksqrC"
assert old in s
s = s.replace(old, "  s'.fsBase = s.fsBase ∧ s'.df = s.df ∧ natVal s'.mem zp zl = natVal s.mem xp xl * natVal s.mem xp xl ∧\n    ∃ (L' : List (Nat × Nat)) (b' : Nat), LiveExt R L L' ∧ b - ksqrC")
# entry: return address on the stack, X15 = 0, DF clear, Go amd64 argument registers
old = re.search(r"@\[reducible\] def Entry \(a : Args\) \(s : State\) : Prop :=\n(.*\n){2}", s).group(0)
s = s.replace(old, """@[reducible] def Entry (a : Args) (s : State) : Prop :=
  s.mem.readLE (s.regs 4).toNat 8 < 2 ^ 47 ∧ s.xmm 15 = 0#128 ∧ s.df = false ∧ s.regs 0 = a.a0 ∧ s.regs 3 = a.a1 ∧
    s.regs 1 = a.a2 ∧ s.regs 7 = a.a3 ∧ s.regs 6 = a.a4 ∧ s.regs 8 = a.a5 ∧ s.regs 9 = a.a6
""")
old = re.search(r"/-- the callee-saved part of every member's post -/\n@\[reducible\] def Kept \(s s' : State\) : Prop :=\n.*\n", s).group(0)
s = s.replace(old, """/-- the callee-saved part of every member's post (as `StackNat.RegsOK`) -/
@[reducible] def Kept (s s' : State) : Prop :=
  s'.regs 4 = s.regs 4 + 8 ∧ s'.regs 5 = s.regs 5 ∧ s'.regs 14 = s.regs 14 ∧ s'.xmm 15 = s.xmm 15
""")
s = s.replace("`Common/SqrCost.lean`): an inner call", "`Common/SqrCost.lean`; amd64 frame sizes equal arm64's): an inner call")
s = s.replace("# The squaring SCC `{nat.sqr, karatsubaSqr}` (go-bigmodexpfix natmul.go:73 / :257), arm64 — statements",
  "# The squaring SCC `{nat.sqr, karatsubaSqr}` (go-bigmodexpfix natmul.go:73 / :257), amd64 — statements\n\nGENERATED by scripts/gen/port-sqrdefs-amd64.py from Arm64/Nat/SqrDefs.lean (then reviewed); keep the two in step.")
s = s.replace("`nat.sqr` (args `X0..X2 = z`, `X3 = stk`, `X4..X6 = x`): frame 176 (`MOVD.W R30, -176(RSP)`), spills up to `SP + 64`\n(`above = 64`). `karatsubaSqr` (args `X0 = stk`, `X1..X3 = z`, `X4..X6 = x`): frame 320, spills up to `SP + 48`.",
  "`nat.sqr` (`0x5f0fe0`; args `AX, BX, CX = z`, `DI = stk`, `SI, R8, R9 = x`): `PUSHQ BP; SUBQ $0xa0` + return address =\n176, spills up to `RSP + 64` (`above = 64`). `karatsubaSqr` (`0x5f2380`; args `AX = stk`, `BX, CX, DI = z`, `SI, R8, R9 = x`):\n`SUBQ $0x130` = 320, spills up to `RSP + 48`. Posts: `fsBase`/DF unchanged (AMD64 DF CONVENTION).")
if not s.startswith("import"):
    pass
s = s.replace("import FvModexp.Proofs.Common.SqrCost\n", "import FvModexp.Proofs.Common.SqrCost\n\nset_option autoImplicit false\n", 1)
open(dst, "w").write(s)
