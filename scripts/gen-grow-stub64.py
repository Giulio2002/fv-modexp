#!/usr/bin/env python3
"""Assemble scripts/grow-stub64.s (the general 8-byte growslice witness stub, amd64) with GNU as and print the Lean
byte list `grCode64` (Witness/Stubs.lean) and its labels. Usage: scripts/gen-grow-stub64.py (needs as, objcopy, nm)."""
import os, subprocess, tempfile
here = os.path.dirname(os.path.abspath(__file__))
with tempfile.TemporaryDirectory() as d:
    o, b = os.path.join(d, 'gr.o'), os.path.join(d, 'gr.bin')
    subprocess.run(['as', '-o', o, os.path.join(here, 'grow-stub64.s')], check=True)
    subprocess.run(['objcopy', '-O', 'binary', '-j', '.text', o, b], check=True)
    labels = subprocess.run(['nm', o], check=True, capture_output=True, text=True).stdout.split('\n')
    bs = open(b, 'rb').read()
labs = sorted((int(l.split()[0], 16), l.split()[2]) for l in labels if l.strip())
print('-- generated by scripts/gen-grow-stub64.py; labels: ' + ' '.join('%s=0x%x' % (n, a) for a, n in labs if not n.startswith('C') or n in ('C0', 'C66')) + ', %d bytes' % len(bs))
print('def grCode64 : List Nat :=\n  [' + ',\n   '.join(', '.join('0x%02x' % x for x in bs[i:i + 24]) for i in range(0, len(bs), 24)) + ']')
