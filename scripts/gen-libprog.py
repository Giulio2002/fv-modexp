#!/usr/bin/env python3
"""gen-libprog.py EXTRACTED.lean NAME OUT.lean -- copy a `janus extract` Extracted.lean into an Extracted-free
library program module FvModexp.Lib.NAME (same segments, stubs, exit address, entry). Generated; do not edit."""
import sys, re
src, name, out = sys.argv[1:4]
t = open(src).read()
t = t.replace("namespace Extracted", f"namespace FvModexp.Lib.{name}").replace("end Extracted", f"end FvModexp.Lib.{name}")
t = re.sub(r"/-!.*?-/", "", t, count=1, flags=re.S)
hdr = f"/-! GENERATED by scripts/gen-libprog.py from a `janus extract` of the pinned harness ({name}); do not edit.\nThe row proof checks `Extracted.program = FvModexp.Lib.{name}.program` by `rfl`. -/\n"
t = t.replace("import Janus\n", "import Janus\n\n" + hdr, 1)
open(out, "w").write(t)
