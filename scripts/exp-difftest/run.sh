#!/bin/bash
# Differential test: the Nat-level exponentiation models (lean/FvModexp/Proofs/Common/Exp*.lean) against the real
# go-bigmodexpfix f9e208c548ab internal functions (montgomery, computeMontgomeryk0, modularInverseModPowerOfTwo,
# subMod2N, expNNOddMontgomeryWindowSize{2,4}, expNNPowerOfTwo, expNNSlow, expNNEven, expNN) on random inputs.
# Copies the module from GOMODCACHE into a temp dir, adds fvexport.go (exports the unexported functions), runs main.go
# which prints `#guard` lines, then checks them with Lean.  Usage: scripts/exp-difftest/run.sh  (from the repo root)
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
SRC=${GOMODCACHE:-$HOME/go/pkg/mod}/github.com/ethereum/go-bigmodexpfix@v0.0.0-20250911101455-f9e208c548ab
T=$(mktemp -d)
cp -r "$SRC" "$T/mod"; chmod -R u+w "$T/mod"; rm -f "$T"/mod/src/math/big/*_test.go
cp "$ROOT/scripts/exp-difftest/fvexport.go.txt" "$T/mod/src/math/big/fvexport.go"
mkdir "$T/drv"; cp "$ROOT/scripts/exp-difftest/main.go" "$T/drv/"; cp "$T/mod/go.sum" "$T/drv/"
printf 'module drv\ngo 1.24.0\nrequire github.com/ethereum/go-bigmodexpfix v0.0.0\nreplace github.com/ethereum/go-bigmodexpfix => ../mod\n' > "$T/drv/go.mod"
(cd "$T/drv" && GOTOOLCHAIN=local GOFLAGS=-mod=mod GOPROXY=off go run .) > "$T/guards.lean"
{ head -1 "$T/guards.lean"; echo '-- GENERATED by scripts/exp-difftest/run.sh: go-bigmodexpfix f9e208c548ab internal functions vs the Lean models (do not edit).'; tail -n +2 "$T/guards.lean"; } > "$ROOT/lean/tests/ExpDiff.lean"
cd "$ROOT/lean" && lake env lean tests/ExpDiff.lean && echo "exp-difftest: $(grep -c '^#guard' tests/ExpDiff.lean) guards OK"
rm -rf "$T"
