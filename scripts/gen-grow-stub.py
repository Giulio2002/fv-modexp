def addsh(d,n,m,sh=0): return 0x8b000000|m<<16|sh<<10|n<<5|d
def subsh(d,n,m): return 0xcb000000|m<<16|n<<5|d
def cmpr(n,m): return 0xeb000000|m<<16|n<<5|31
def cmpi(n,i): assert i<4096; return 0xf1000000|i<<10|n<<5|31
def mov(d,m): return 0xaa0003e0|m<<16|d
def movz(d,i,hw=0): assert i<65536; return 0xd2800000|hw<<21|i<<5|d
def addi(d,n,i): return 0x91000000|i<<10|n<<5|d
def subi(d,n,i): return 0xd1000000|i<<10|n<<5|d
def udiv(d,n,m): return 0x9ac00800|m<<16|n<<5|d
def mul(d,n,m): return 0x9b000000|m<<16|31<<10|n<<5|d
def bcond(cur,tgt,c): o=(tgt-cur)&0x7ffff; return 0x54000000|o<<5|c
def b(cur,tgt): return 0x14000000|((tgt-cur)&0x3ffffff)
def cbz(cur,tgt,r): return 0xb4000000|((tgt-cur)&0x7ffff)<<5|r
