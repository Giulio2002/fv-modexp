#!/usr/bin/env python3
"""gen-libprog-sub.py EXTRACTED.lean NAME OUT.lean FN... -- (agent expmc; after fv-modexp-asm scripts/gen-libprog.py)
Copy the segments FN... (full symbol names, or suffixes after 'math/big.') of a `janus extract` Extracted.lean, with
its stubs, exit address and runtime-contract addresses, into an Extracted-free library program module
`FvModexp.Lib.NAME` (no data objects). Generated; do not edit by hand. Proofs about the library program move to the
row's program with `CodeIn` (`codeIn_lib`), checked by `decide` against the row's `Extracted.program`."""
import sys, re
src, name, out, *fns = sys.argv[1:]
t = open(src).read()
isa64 = "Amd64.Segment" in t
segs = {}
for m in re.finditer(r'def (seg\d+) : (?:Amd64\.)?Segment :=\n  \{ name := "([^"]+)", base := (0x[0-9a-f]+), (words|bytes) := \[(.*?)\] \}', t, re.S):
    segs[m.group(2)] = m.group(0)
pick = []
for f in fns:
    full = f if f in segs else "github.com/ethereum/go-bigmodexpfix/src/math/big." + f
    if full not in segs: sys.exit("no segment " + f)
    pick.append(full)
stubs = re.search(r'def stubs : List (?:Amd64\.)?Stub := \[.*?\]\n', t, re.S).group(0)
contracts = re.search(r'def contracts : List \(String × Nat\) := \[.*?\]\n', t, re.S).group(0)
exit_ = re.search(r'def exitAddr : Nat := .*\n', t).group(0)
ty = "Amd64.Program" if isa64 else "Program"
seg_ty = "Amd64.Segment" if isa64 else "Segment"
o = ["import Janus", "",
     f"/-! GENERATED by scripts/gen-libprog-sub.py from the pinned Run extraction ({src}); do not edit.",
     f"Library program {name}: segments {', '.join(pick)}. -/", "",
     f"namespace FvModexp.Lib.{name}", "open Janus", ""]
names = []
for i, f in enumerate(pick):
    body = segs[f]
    body = re.sub(r'^def seg\d+ :', f'def lseg{i} :', body)
    o.append(body); o.append(""); names.append(f"lseg{i}")
o.append(f"def segments : List {seg_ty} := [{', '.join(names)}]")
o.append(""); o.append(stubs.rstrip()); o.append(""); o.append(exit_.rstrip()); o.append(""); o.append(contracts.rstrip()); o.append("")
o.append(f"def program : {ty} :=\n  {{ segments := segments, stubs := stubs, exitAddr := exitAddr, contracts := contracts }}")
o.append(""); o.append(f"end FvModexp.Lib.{name}"); o.append("")
open(out, "w").write("\n".join(o))
