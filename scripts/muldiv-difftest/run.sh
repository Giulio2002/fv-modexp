#!/bin/bash
# Differential test: the mathdiv Nat-level models (limb lists) against the real go-bigmodexpfix f9e208c548ab internals
# (setBytes, Int.Bytes, bitLen, nat.mul/sqr, basicSqr, karatsuba(Sqr), divBasic, divRecursive, nat.div) on random inputs.
# Same scheme as scripts/exp-difftest: copy the module, add fvexport.go, run main.go (prints #guard lines), check with Lean.
# Usage: scripts/muldiv-difftest/run.sh  (from the repo root).  Sanity check of the transcriptions, not part of the proof.
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
SRC=${GOMODCACHE:-$HOME/go/pkg/mod}/github.com/ethereum/go-bigmodexpfix@v0.0.0-20250911101455-f9e208c548ab
T=$(mktemp -d)
cp -r "$SRC" "$T/mod"; chmod -R u+w "$T/mod"; rm -f "$T"/mod/src/math/big/*_test.go
cp "$ROOT/scripts/muldiv-difftest/fvexport.go.txt" "$T/mod/src/math/big/fvexport_muldiv.go"
mkdir "$T/drv"; cp "$ROOT"/scripts/muldiv-difftest/*.go "$T/drv/"; cp "$T/mod/go.sum" "$T/drv/" 2>/dev/null || true
printf 'module drv\ngo 1.24.0\nrequire github.com/ethereum/go-bigmodexpfix v0.0.0\nreplace github.com/ethereum/go-bigmodexpfix => ../mod\n' > "$T/drv/go.mod"
(cd "$T/drv" && GOTOOLCHAIN=local GOFLAGS=-mod=mod GOPROXY=off go run .) > "$T/guards.lean"
mkdir -p "$ROOT/lean/tests"
{ echo '-- GENERATED by scripts/muldiv-difftest/run.sh: go-bigmodexpfix f9e208c548ab internals vs the mathdiv Lean models (do not edit).'; cat "$T/guards.lean"; } > "$ROOT/lean/tests/MulDivDiff.lean"
cd "$ROOT/lean" && lake env lean tests/MulDivDiff.lean && echo "muldiv-difftest: $(grep -c '^#guard' tests/MulDivDiff.lean) guards OK"
rm -rf "$T"
