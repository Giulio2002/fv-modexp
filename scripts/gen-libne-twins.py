#!/usr/bin/env python3
"""gen-libne-twins.py: generate the LibNE twins (agent expmc, s31) of nat.expNN's machine-run (janus_run) path modules.

nat.expNN's `expNNEven` call needs the recursive pair's program LibNE (LibN ∪ {expNNEven}); a path lemma proved on
`LibN.program.link impl` in continuation form cannot be lifted (its continuations are on LibN), so the modules on the
way to the even call get a twin `<M>E.lean` on `LibNE.program.link impl`: every theorem of <M> renamed `<name>E`,
`LibN.program` -> `LibNE.program`, imports of twinned modules -> their twins; definitions are NOT duplicated (the twin
imports the original module). Usage: scripts/gen-libne-twins.py [--check]  (writes / diffs lean/.../Arm64/Exp/<M>E.lean)
"""
import re, sys, os
D = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'lean', 'FvModexp', 'Proofs', 'Arm64', 'Exp')
TWINS = ['NPro', 'NTriv', 'NMk', 'NDisp', 'NStkNil', 'NGet', 'NNilT', 'NNilN', 'NNilJ']
PFX = 'FvModexp.Proofs.Arm64.Exp.'

def thm_names(src):
    # only the theorems about the program (their chunk mentions `LibN.program`) are twinned
    out = []
    for c in re.split(r'\n\s*\n', src):
        m = re.search(r'^(?:private )?theorem (\w+)', c, re.M)
        if m and 'LibN.program' in c: out.append(m.group(1))
    return out

allnames = {}
for m in TWINS:
    for n in thm_names(open(os.path.join(D, m + '.lean')).read()):
        allnames[n] = n + 'E'

def gen(m):
    src = open(os.path.join(D, m + '.lean')).read()
    head, _, body = src.partition('\nnamespace FvModexp.Arm64.ExpN\n')
    body = body.rsplit('end FvModexp.Arm64.ExpN', 1)[0]
    chunks = re.split(r'\n\s*\n', body)
    keep = []
    for c in chunks:
        lines = [l for l in c.strip().splitlines() if l.strip()]
        first = next((l for l in lines if not l.startswith('set_option') and not l.startswith('/-') and
                      not l.startswith('@[') and not l.lstrip().startswith('-/') and not l.startswith(' ')), '')
        if re.match(r'(private )?theorem ', first) and 'LibN.program' in c:
            keep.append(c.strip('\n'))
    out = '\n\n'.join(keep)
    out = out.replace('LibN.program', 'LibNE.program')
    out = re.sub(r'\b(' + '|'.join(map(re.escape, sorted(allnames, key=len, reverse=True))) + r')\b',
                 lambda mo: allnames[mo.group(1)], out)
    imps = re.findall(r'^import (\S+)', head, re.M)
    newimps = [PFX + m]
    for i in imps:
        base = i[len(PFX):] if i.startswith(PFX) else None
        if base in TWINS: newimps.append(PFX + base + 'E')
    newimps.append(PFX + 'LibNE')
    opens = re.findall(r'^open .*$', head, re.M)
    hdr = '\n'.join('import ' + i for i in dict.fromkeys(newimps))
    hdr += ('\n\n/-! GENERATED by scripts/gen-libne-twins.py from `%s.lean` (do not edit): its theorems on '
            '`LibNE.program.link impl` (the recursive pair nat.expNN ↔ nat.expNNEven), names suffixed `E`. -/\n\n' % m)
    hdr += '\n'.join(opens) + '\n\nset_option autoImplicit false\n\nnamespace FvModexp.Arm64.ExpN\n\n'
    return hdr + out + '\n\nend FvModexp.Arm64.ExpN\n'

bad = 0
for m in TWINS:
    t = gen(m); p = os.path.join(D, m + 'E.lean')
    if '--check' in sys.argv:
        if not os.path.exists(p) or open(p).read() != t: print('DIFFERS', p); bad = 1
    else:
        open(p, 'w').write(t); print('wrote', p)
sys.exit(bad)
